/**
 * Процент прибыли инвестора — от 0 до 100: это доля прибыли, которую заработали
 * его деньги, и больше неё отдать нельзя. Раньше форма принимала и 110% — так
 * пытались передать участникам пула плату за управление, а в итоге инвесторам
 * уходило больше прибыли, чем заработано. Для этого теперь есть «Доля за
 * управление» в меню счёта пула.
 */
export const percentError = (value: string): string | undefined => {
  if (value.trim() === '') return undefined;
  const n = Number(value.replace(',', '.'));
  if (!Number.isFinite(n) || n < 0) return 'Введите число от 0 до 100';
  if (n > 100) return 'Не больше 100%. Плату за управление пулом участникам — в меню счёта: «Доля за управление»';
  return undefined;
};
