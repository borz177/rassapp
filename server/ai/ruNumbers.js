/**
 * Числа словами → цифры, для расшифровки голосового.
 *
 * Модель, переводя числа в цифры сама, путала составные: «девятьсот шестьдесят
 * пять» → «9605», «двадцать два» → «202», в телефоне терялись и менялись цифры.
 * Поэтому расшифровка пишет числа словами, как произнесены, а складывает их код.
 *
 *  «пятьдесят тысяч» → 50000, «двадцать пять процентов» → 25 процентов,
 *  «восемь девятьсот шестьдесят пять семьсот семьдесят семь семьдесят двадцать семь»
 *  → 89657777027 (подряд три и больше чисел или 10+ цифр — это телефон: склеиваем).
 */

const UNITS = {
  ноль: 0, нуль: 0, один: 1, одна: 1, одну: 1, одно: 1, два: 2, две: 2, три: 3, четыре: 4,
  пять: 5, шесть: 6, семь: 7, восемь: 8, девять: 9,
};
const TEENS = {
  десять: 10, одиннадцать: 11, двенадцать: 12, тринадцать: 13, четырнадцать: 14, пятнадцать: 15,
  шестнадцать: 16, семнадцать: 17, восемнадцать: 18, девятнадцать: 19,
};
const TENS = {
  двадцать: 20, тридцать: 30, сорок: 40, пятьдесят: 50, шестьдесят: 60, семьдесят: 70, восемьдесят: 80, девяносто: 90,
};
const HUNDREDS = {
  сто: 100, двести: 200, триста: 300, четыреста: 400, пятьсот: 500, шестьсот: 600, семьсот: 700, восемьсот: 800, девятьсот: 900,
};
const SCALES = { тысяча: 1e3, тысячи: 1e3, тысяч: 1e3, тысячу: 1e3, миллион: 1e6, миллиона: 1e6, миллионов: 1e6 };

const kind = (w) => (w in UNITS ? 'u' : w in TEENS ? 't' : w in TENS ? 'x' : w in HUNDREDS ? 'h' : w in SCALES ? 's' : null);
const val = (w) => UNITS[w] ?? TEENS[w] ?? TENS[w] ?? HUNDREDS[w] ?? SCALES[w];

/** Слова одного числа подряд → список чисел: «семь семь» — два числа, «семьдесят семь» — одно */
const parseRun = (words) => {
  const out = [];
  let total = 0;      // уже набранные тысячи/миллионы
  let cur = 0;        // текущая сотня
  let slot = 4;       // старший занятый разряд текущей сотни: 3 — сотни, 2 — десятки, 1 — единицы, 4 — пусто
  let open = false;   // число начато
  const flush = () => { if (open) out.push(total + cur); total = 0; cur = 0; slot = 4; open = false; };
  for (const w of words) {
    const k = kind(w);
    const v = val(w);
    if (k === 's') {
      // «тысяча» без числа перед ней — одна тысяча
      total += (open ? (cur || 1) : 1) * v; cur = 0; slot = 4; open = true;
      continue;
    }
    if (w === 'ноль' || w === 'нуль') { flush(); out.push(0); continue; }
    const rank = k === 'h' ? 3 : k === 'x' || k === 't' ? 2 : 1;
    // Складывается, только если разряд младше уже занятого: «семьсот семьдесят семь» —
    // одно число, «семь семь», «семьдесят двадцать» — разные. После «-надцать» единиц нет
    const fits = open && rank < slot && !(slot === 2 && cur % 100 >= 10 && cur % 100 < 20);
    if (!fits) flush();
    cur += v; slot = k === 't' ? 1 : rank; open = true;
  }
  flush();
  return out;
};

// Слово-число с приклеенной пунктуацией: «семь,» «ноль.»
const WORD_RE = /^([а-яё]+)([.,!?;:]*)$/i;

/** Заменить в тексте все числа словами на цифры */
const wordsToDigits = (text) => {
  // «полтора миллиона», «полторы тысячи» — отдельно: дробь только с тысячей/миллионом
  const src = String(text || '')
    .replace(/(^|[^а-яё])полтор[аы]\s+миллион[а-я]*/gi, '$11500000')
    .replace(/(^|[^а-яё])полтор[аы]\s+тысяч[а-я]*/gi, '$11500');
  const tokens = src.split(/(\s+)/);
  const res = [];
  let run = [];            // { word, raw } подряд идущих чисел
  const end = () => {
    if (!run.length) return;
    const nums = parseRun(run.map(r => r.word));
    const tail = run[run.length - 1].punct || '';
    // Три и больше чисел подряд или 10+ цифр — номер телефона: склеиваем
    const digits = nums.map(String).join('');
    const phone = nums.length >= 3 || digits.length >= 10;
    res.push((phone ? digits : nums.join(' ')) + tail);
    run = [];
  };
  for (const t of tokens) {
    if (/^\s+$/.test(t)) { if (!run.length) res.push(t); continue; }
    const m = t.match(WORD_RE);
    const w = m && m[1].toLowerCase().replace(/ё/g, 'е');
    // «-» и пунктуация внутри числа («семь, семь») номер не рвут, а точка — рвёт
    if (w && kind(w)) {
      if (run.length && /[.!?]/.test(run[run.length - 1].punct || '')) { end(); res.push(' '); }
      run.push({ word: w, punct: m[2] });
      continue;
    }
    if (run.length) { end(); res.push(' '); }
    res.push(t);
  }
  end();
  // «плюс 79281112233» → «+79281112233»
  return res.join('').replace(/ {2,}/g, ' ').replace(/(^|\s)плюс\s+(?=\d)/gi, '$1+').trim();
};

module.exports = { wordsToDigits, parseRun };
